def evaluate_return(order_id:str)->dict:
  order = ORDERS.get(order_id)

  if order is None:
    return {'ok':False, 'error':'ORDER_NOT_FOUND'}

  eligible = order.delivered_days_ago <= 14

  return {
        'ok':True,
        'data':{
            'order_id':order_id,
            'eligible':eligible,
            'reason': 'WITHIN_WINDOW' if eligible else 'WINDOW_EXPIRED'
        }
    }

