#Siparis Bilgilerini Getirir
def get_order(order_id:str)->dict:
  order = ORDERS.get(order_id)
  if order is None:
    return {'ok':False, 'error':'ORDER_NOT_FOUND'}

  return{'ok':True, 'data':asdict(order)}

#ORDERS[order_id] yerine ORDERS.get(order_id) kullanmamizin sebebi sozlukte olmayan bir veri cagirilmasi durumunda KeyError almak yerine varsayilan olarak None gormek icin.
#Stok miktarini kontrol eder
def check_stock(item:str)->dict:
  return {'ok':True, 'data':{'item':item, 'available':STOCK.get(item,0)}}

