"""#Single Agent Orchestrator"""

import re

def route(message:str)-> tuple[str, dict] | None:
  order_match = re.search(r'ORD-\d+', message.upper())
  lower = message.lower()
  if 'iade' in lower and order_match:
    return 'evaluate_return', {'order_id': order_match.group()}
  if 'siparis' in lower and order_match:
    return 'get_order', {'order_id':order_match.group()}
  if 'stok' in lower:
    item = next((x for x in STOCK if x.lower() in lower), None)
    if item:
      return 'check_stock', {'item':item}

  return None


class SingleAgent:
  def run(self, message:str)-> dict:
    decision = route(message)
    if decision is None:
      return {'ok':False, 'error':'UNSUPPORTED_REQUEST'}

    name, args = decision
    return {'selected_tool':name, 'result':execute_tool(name,args)}

agent = SingleAgent()
